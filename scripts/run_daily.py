"""Daily orchestrator for instagram-daily-mood (after the fetch step).

The fetch step (public Instagram trend discovery) is done by the agent
and normalized with normalize.py into data/raw/<date>.json. The
illustration and the animation are generated by the agent's media
pipeline: a painterly illustration (style reference: the user's
reference image, kept private and NOT committed to this repo) is
animated image-to-video. This script runs the analysis step and
reports the day's dominant emotion so the illustration can reflect it:

  python run_daily.py --date 2026-10-29

It writes data/<date>.json. After it runs, generate
assets/<date>.png (illustration) and assets/<date>.mp4 (animation),
copy the mp4 to assets/latest.mp4, and update README.md.

Note: this VM's no_proxy list contains bracketed IPv6 entries that
break httpx's proxy handling inside huggingface_hub (InvalidURL:
Invalid port). The model hub is not a no_proxy host, so a minimal
list is safe here and keeps the download working.
"""
import argparse
import json
import os
import subprocess
import sys
from pathlib import Path


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--date", required=True)
    parser.add_argument("--python", default=sys.executable)
    args = parser.parse_args()

    root = Path(__file__).resolve().parent.parent
    env = {k: v for k, v in os.environ.items() if k not in ("no_proxy", "NO_PROXY")}
    env["no_proxy"] = "localhost,127.0.0.1"
    env["NO_PROXY"] = "localhost,127.0.0.1"
    subprocess.run(
        [args.python, str(root / "scripts" / "analyze.py"), "--date", args.date],
        cwd=root,
        check=True,
        env=env,
    )
    result = json.loads((root / "data" / f"{args.date}.json").read_text(encoding="utf-8"))
    print(f"daily analysis complete for {args.date}: dominant={result['dominant_emotion']}")
    print("next: generate assets/<date>.png + assets/<date>.mp4 via the media pipeline,")
    print("copy the mp4 to assets/latest.mp4, and update README.md.")


if __name__ == "__main__":
    main()
